export function focusHint(agentSlug: AgentSlugName): string {
  switch (agentSlug) {
    case 'lawyer':
      return 'Сейчас пользователь открыл режим «Юрист». Веди разбор от права, но коротко отметь налоговые и бизнес-последствия, если они есть.';
    case 'consultant':
      return 'Сейчас пользователь открыл режим «Консультант». Веди разбор от стратегии и цифр, но коротко отметь налоги и юридические ограничения.';
    case 'team':
      return 'Режим «вся команда»: дай три коротких блока (Бухгалтерия / Право / Бизнес) и общий вывод с приоритетами.';
    case 'accountant':
    default:
      return 'Сейчас пользователь открыл режим «Бухгалтер». Веди разбор от налогов и отчётности, но коротко отметь право и целесообразность, если они есть.';
  }
}

export function formatCompanyContext(company?: Record<string, unknown>): string {
  if (!company) {
    return 'Контекст компании не передан. Если нужно — уточни 1–2 факта.';
  }
  const rows = [
    ['Название', company.name],
    ['Тип', company.type],
    ['БИН/ИИН', company.binIin],
    ['Сфера', company.industry],
    ['Налоговый режим', company.taxRegime],
    ['Сотрудники', company.employeeCount],
    ['Главная задача', company.primaryGoal],
  ]
    .filter(([, value]) => value !== undefined && value !== null && String(value).trim() !== '')
    .map(([key, value]) => `- ${key}: ${String(value)}`)
    .join('\n');
  return rows ? `Данные компании из кабинета:\n${rows}` : 'Контекст компании пустой.';
}

export function buildSystemPrompt(params: Pick<ChatParams, 'agentSlug' | 'companyContext'>): string {
  return [
    BIZAFFLE_SYSTEM_PROMPT,
    '',
    '==================================================',
    'СЕССИЯ',
    '==================================================',
    '',
    focusHint(params.agentSlug),
    '',
    formatCompanyContext(params.companyContext),
  ].join('\n');
}
